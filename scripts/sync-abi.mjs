// Copies the compiled AgentRegistry ABI into the web app as a typed constant.
// Run `forge build` in contracts/ first, then `node scripts/sync-abi.mjs`.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const artifact = resolve(root, 'contracts/out/AgentRegistry.sol/AgentRegistry.json')
const target = resolve(root, 'web/src/abi/AgentRegistry.ts')

const { abi } = JSON.parse(readFileSync(artifact, 'utf8'))

writeFileSync(
  target,
  `// Generated by scripts/sync-abi.mjs. Do not edit by hand.\nexport const agentRegistryAbi = ${JSON.stringify(abi, null, 2)} as const\n`,
)

console.log(`Wrote ${abi.length} ABI entries to ${target}`)
